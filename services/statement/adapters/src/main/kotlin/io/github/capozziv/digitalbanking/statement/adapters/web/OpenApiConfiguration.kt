package io.github.capozziv.digitalbanking.statement.adapters.web

import io.swagger.v3.oas.models.Components
import io.swagger.v3.oas.models.OpenAPI
import io.swagger.v3.oas.models.info.Info
import io.swagger.v3.oas.models.media.Content
import io.swagger.v3.oas.models.media.MediaType
import io.swagger.v3.oas.models.media.Schema
import io.swagger.v3.oas.models.responses.ApiResponse
import io.swagger.v3.oas.models.security.SecurityRequirement
import io.swagger.v3.oas.models.security.SecurityScheme
import org.springdoc.core.customizers.OpenApiCustomizer
import org.springframework.context.annotation.Bean
import org.springframework.context.annotation.Configuration

/**
 * OpenAPI contract of the statement API, generated by springdoc from the controller (`/v3/api-docs`).
 * The per-operation responses are annotated on the controller; this adds what applies to every operation.
 */
@Configuration
class OpenApiConfiguration {
    @Bean
    fun statementOpenApi(): OpenAPI =
        OpenAPI()
            .info(
                Info()
                    .title("statement")
                    .version("v1")
                    .description(DESCRIPTION),
            ).components(
                Components().addSecuritySchemes(
                    BEARER_AUTH,
                    SecurityScheme().type(SecurityScheme.Type.HTTP).scheme("bearer").bearerFormat("JWT"),
                ),
            ).addSecurityItem(SecurityRequirement().addList(BEARER_AUTH))

    /** Every operation can fail with an unexpected error, answered by the generic handler as 500 internal-error. */
    @Bean
    fun internalErrorResponseCustomizer(): OpenApiCustomizer =
        OpenApiCustomizer { openApi ->
            openApi.paths.orEmpty().values.flatMap { it.readOperations() }.forEach { operation ->
                operation.responses.addApiResponse(
                    "500",
                    ApiResponse()
                        .description("${ApiDocs.PROBLEMS}internal-error: unexpected error; the detail does not expose the cause")
                        .content(
                            Content().addMediaType(
                                ApiDocs.PROBLEM_JSON,
                                MediaType().schema(Schema<Any>().`$ref`("#/components/schemas/ProblemDetail")),
                            ),
                        ),
                )
            }
        }

    private companion object {
        const val BEARER_AUTH = "bearerAuth"

        val DESCRIPTION =
            """
            Statement of the simulated digital bank: the ledger entries of an account, projected from the events of accounts.

            - Every request carries `Authorization: Bearer <JWT>` (scheme `bearerAuth`). No token, or an invalid or
              expired one, is `401 /problems/unauthorized`.
            - A customer reads only the statements of their own accounts; an admin reads any. The account of another
              customer answers `404 /problems/account-not-found`, the same as an account that does not exist.
            - The list is newest first (highest ledger sequence first); `limit` is 1 to 100 (default 20).
            - `nextCursor` is opaque and null on the last page. Entries arrive asynchronously, so a just-made
              operation may take a moment to show up.
            - Amounts are in cents; `balanceAfter` is negative when the account is in overdraft.
            - Errors are Problem Details (RFC 9457, `application/problem+json`). Errors of this API have a relative
              `type` `/problems/<slug>`; `400 /problems/validation-error` lists the invalid fields in `errors`.
            - Errors raised by the framework itself (404 unknown route, 405 method not allowed, ...) are Problem
              Details without a `type` member, which RFC 9457 defines as `about:blank`.
            - `X-Correlation-Id` is accepted on every request (generated when absent or invalid) and returned on every
              response.
            """.trimIndent()
    }
}

/** Texts shared by the OpenAPI annotations of the controller. */
internal object ApiDocs {
    const val PROBLEMS = "/problems/"
    const val PROBLEM_JSON = "application/problem+json"
}
