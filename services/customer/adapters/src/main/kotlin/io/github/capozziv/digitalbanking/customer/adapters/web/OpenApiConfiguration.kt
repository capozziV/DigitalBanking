package io.github.capozziv.digitalbanking.customer.adapters.web

import io.swagger.v3.oas.models.Components
import io.swagger.v3.oas.models.OpenAPI
import io.swagger.v3.oas.models.info.Info
import io.swagger.v3.oas.models.media.Content
import io.swagger.v3.oas.models.media.MediaType
import io.swagger.v3.oas.models.media.Schema
import io.swagger.v3.oas.models.responses.ApiResponse
import io.swagger.v3.oas.models.security.SecurityRequirement
import io.swagger.v3.oas.models.security.SecurityScheme
import org.springdoc.core.customizers.OpenApiCustomizer
import org.springframework.context.annotation.Bean
import org.springframework.context.annotation.Configuration

/**
 * OpenAPI contract of the customer API, generated by springdoc from the controllers (`/v3/api-docs`).
 * The per-operation responses are annotated on the controllers; this adds what applies to every operation.
 */
@Configuration
class OpenApiConfiguration {
    @Bean
    fun customerOpenApi(): OpenAPI =
        OpenAPI()
            .info(Info().title("customer").version("v1").description(DESCRIPTION))
            .components(
                Components().addSecuritySchemes(
                    BEARER_AUTH,
                    SecurityScheme().type(SecurityScheme.Type.HTTP).scheme("bearer").bearerFormat("JWT"),
                ),
            ).addSecurityItem(SecurityRequirement().addList(BEARER_AUTH))

    /** Every operation needs a token and can fail with an unexpected error. */
    @Bean
    fun commonErrorResponsesCustomizer(): OpenApiCustomizer =
        OpenApiCustomizer { openApi ->
            openApi.paths.orEmpty().values.flatMap { it.readOperations() }.forEach { operation ->
                operation.responses.addApiResponse("401", problemResponse("unauthorized: no token, or an invalid or expired one"))
                operation.responses.addApiResponse("403", problemResponse("forbidden: the token is not allowed on this route"))
                operation.responses.addApiResponse(
                    "500",
                    problemResponse("internal-error: unexpected error; the detail does not expose the cause"),
                )
            }
        }

    private fun problemResponse(description: String) =
        ApiResponse()
            .description("${ApiDocs.PROBLEMS}$description")
            .content(
                Content().addMediaType(
                    ApiDocs.PROBLEM_JSON,
                    MediaType().schema(Schema<Any>().`$ref`("#/components/schemas/ProblemDetail")),
                ),
            )

    private companion object {
        const val BEARER_AUTH = "bearerAuth"

        val DESCRIPTION =
            """
            Customers of the simulated digital bank: registration, status and the lookup the other services make.

            - Every route needs a bearer JWT (`bearerAuth`). The customer id is the `sub` of the user token.
            - `/customers/**`: the customer (or an admin acting as the customer of its own `sub`); `/admin/**`: admin
              only; `/internal/**`: a service token only (machine token with the `digitalbanking/internal` scope).
            - Errors are Problem Details (RFC 9457, `application/problem+json`). Errors of this API have a relative
              `type` `/problems/<slug>`; `400 /problems/validation-error` lists the invalid fields in `errors`.
            - Errors raised by the framework itself (404 unknown route, 405 method not allowed, 415 unsupported
              media type, ...) are Problem Details without a `type` member, which RFC 9457 defines as `about:blank`.
            - `X-Correlation-Id` is accepted on every request (generated when absent or invalid) and returned on
              every response.
            """.trimIndent()
    }
}
