package io.github.capozziv.digitalbanking.customer.bootstrap

import io.github.capozziv.digitalbanking.testing.security.JwtTestSupport
import org.springframework.boot.test.context.SpringBootTest
import org.springframework.context.annotation.Import
import org.springframework.jdbc.core.simple.JdbcClient
import org.springframework.jdbc.datasource.DriverManagerDataSource
import org.springframework.test.context.DynamicPropertyRegistry
import org.springframework.test.context.DynamicPropertySource
import org.springframework.test.context.TestPropertySource
import org.testcontainers.postgresql.PostgreSQLContainer

/**
 * Base of every integration test of the customer service. One PostgreSQL container is shared by all subclasses
 * (singleton container, so the cached Spring context keeps a valid connection). The application connects as
 * [APP_USER] (no DELETE); Flyway runs as the container's owner user, mirroring customer_owner / customer_app of the
 * local environment. Tokens come from [JwtTestSupport] (a decoder that trusts a key generated by the test).
 * The outbox relay is off, so outbox rows stay as the operations wrote them; the relay test turns it on.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@Import(JwtTestSupport.DecoderConfiguration::class)
@TestPropertySource(properties = ["customer.outbox.relay-enabled=false"])
abstract class CustomerIntegrationTest {
    /** JdbcClient connected as the owner user, for setup and inspection outside the application's grants. */
    protected val ownerJdbc: JdbcClient by lazy {
        JdbcClient.create(DriverManagerDataSource(postgres.jdbcUrl, postgres.username, postgres.password))
    }

    /** JdbcClient connected as the application user, to check what the grants allow. */
    protected val appJdbc: JdbcClient by lazy {
        JdbcClient.create(DriverManagerDataSource(postgres.jdbcUrl, APP_USER, APP_PASSWORD))
    }

    /** Marks as published every pending outbox event, such as those left by other tests on the shared database. */
    protected fun markPendingOutboxEventsPublished() {
        ownerJdbc.sql("update outbox set published_at = now() where published_at is null").update()
    }

    companion object {
        const val APP_USER = "customer_app"
        const val APP_PASSWORD = "app"

        @JvmStatic
        val postgres: PostgreSQLContainer =
            PostgreSQLContainer("postgres:17-alpine")
                .withInitScript("db/create-app-role.sql")
                .apply { start() }

        @JvmStatic
        @DynamicPropertySource
        fun databaseProperties(registry: DynamicPropertyRegistry) {
            registry.add("spring.datasource.url") { postgres.jdbcUrl }
            registry.add("spring.datasource.username") { APP_USER }
            registry.add("spring.datasource.password") { APP_PASSWORD }
            registry.add("spring.flyway.user") { postgres.username }
            registry.add("spring.flyway.password") { postgres.password }
            registry.add("spring.flyway.placeholders.appUser") { APP_USER }
        }
    }
}
